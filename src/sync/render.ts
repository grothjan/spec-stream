/**
 * Pure renderer: `render(state) -> DesiredTree`.
 *
 * Maps the in-memory {@link ModelState} to the full set of desired files (a map of
 * relative POSIX path -> file content). It performs **no I/O** — the writer diffs this
 * desired tree against disk and applies the minimal changes.
 *
 * Layout (see docs/local-sync.md), slice-first:
 *
 *   workspace.json
 *   chapters/[chapter-uuid]/
 *     chapter.json, index.md
 *     slices/[slice-uuid]/
 *       slice.json, details.md, comments/[createdAt]_[id]/{comment.json, comment.md}
 *     lanes/[lane-uuid]/
 *       lane.json
 *     elements/[element-uuid]/
 *       element.json, description.md, details.md,
 *       comments/[createdAt]_[id]/{comment.json, comment.md}
 *     scenarios/[scenario-uuid]/
 *       scenario.json
 *   milestones/[milestone-uuid]/{milestone.json, description.md}
 *
 * Names/labels live only in the .json files; directory names are UUIDs.
 */

import {
  type ModelState,
  type ChapterState,
  type SliceState,
  type LaneState,
  type ElementState,
  type MilestoneState,
  type ScenarioState,
  type HtmlSnippetState,
  type Comment,
  parseLaneDetailsKey,
  slicesOfChapter,
  lanesOfChapter,
  elementsInCell,
} from "./model.js";
import { sanitizeSegment, nameSlug } from "./sanitize.js";
import type { DirtySet } from "./reducer.js";

/** A desired file tree: relative POSIX path -> UTF-8 content. */
export type DesiredTree = Map<string, string>;

const GENERATED_MARKER =
  "<!-- Generated by spec-stream — do not edit, changes will be overwritten. -->\n";

/** Render the whole model to a desired file tree. */
export function render(state: ModelState): DesiredTree {
  const tree: DesiredTree = new Map();

  tree.set(
    "workspace.json",
    json({
      id: state.workspaceId,
      name: state.workspaceName,
    }),
  );

  for (const chapter of state.chapters.values()) {
    renderChapter(tree, state, chapter);
  }
  renderSharedLaneDetails(tree, state);
  for (const milestone of state.milestones.values()) {
    renderMilestone(tree, milestone);
  }

  // Render workspace-level HTML snippets.
  for (const snippet of state.htmlSnippets.values()) {
    renderHtmlSnippet(tree, snippet);
  }

  // Build the flat UUID → path index so agents can resolve an id to a directory without
  // recursing the whole tree (path is the directory containing the primary .json).
  renderUuidIndex(tree, state);

  return tree;
}

/**
 * Partial render: only emit files for entities listed in `dirty`, plus the small
 * always-rewrite files (workspace.json, uuid-index.json, and index.md for any chapter
 * whose own data or one of its children changed).
 *
 * Used by the projection to avoid overwriting locally-modified files that were not
 * touched by the applied events. `writeTree` with this partial tree will only
 * overwrite the subset of files that actually changed on the board.
 *
 * `workspace.json` and `uuid-index.json` are always included: they are tiny and must
 * stay consistent with the entity set after any add/remove event.
 *
 * A chapter's `index.md` is regenerated whenever the chapter itself or any of its
 * children (slices, lanes, elements, scenarios) is dirty, because `index.md` is a
 * derived summary that depends on all of them.
 */
export function renderPartial(state: ModelState, dirty: DirtySet): DesiredTree {
  const tree: DesiredTree = new Map();

  // Always rewrite workspace.json and uuid-index.json — tiny, and must stay consistent.
  tree.set("workspace.json", json({ id: state.workspaceId, name: state.workspaceName }));
  renderUuidIndex(tree, state);

  // Determine which chapters need their index.md regenerated.
  // A chapter is "index-dirty" if it or any of its children changed.
  const indexDirtyChapters = new Set<string>(dirty.chapters);
  for (const sliceId of dirty.slices) {
    const c = state.slices.get(sliceId)?.chapterId;
    if (c) indexDirtyChapters.add(c);
  }
  for (const laneId of dirty.lanes) {
    const c = state.lanes.get(laneId)?.chapterId;
    if (c) indexDirtyChapters.add(c);
  }
  for (const elementId of dirty.elements) {
    const c = state.elements.get(elementId)?.chapterId;
    if (c) indexDirtyChapters.add(c);
  }
  for (const scenarioId of dirty.scenarios) {
    const c = state.scenarios.get(scenarioId)?.chapterId;
    if (c) indexDirtyChapters.add(c);
  }

  // Render dirty chapters fully (chapter.json + index.md + all children).
  for (const chapterId of dirty.chapters) {
    const chapter = state.chapters.get(chapterId);
    if (chapter) renderChapter(tree, state, chapter);
    // Deleted chapter: nothing to render; writeTree will prune its directory.
  }

  // Regenerate index.md for chapters with dirty children that weren't fully re-rendered above.
  for (const chapterId of indexDirtyChapters) {
    if (dirty.chapters.has(chapterId)) continue; // already fully rendered
    const chapter = state.chapters.get(chapterId);
    if (chapter) tree.set(`${chapterDir(chapter)}/index.md`, renderChapterIndex(state, chapter));
  }

  // Render dirty slices.
  for (const sliceId of dirty.slices) {
    const slice = state.slices.get(sliceId);
    if (!slice) continue;
    const chapter = state.chapters.get(slice.chapterId);
    if (chapter) renderSlice(tree, state, chapter, slice);
  }

  // Render dirty lanes.
  for (const laneId of dirty.lanes) {
    const lane = state.lanes.get(laneId);
    if (!lane) continue;
    const chapter = state.chapters.get(lane.chapterId);
    if (chapter) renderLane(tree, chapter, lane);
  }

  // Render dirty elements.
  for (const elementId of dirty.elements) {
    const el = state.elements.get(elementId);
    if (!el) continue;
    const chapter = state.chapters.get(el.chapterId);
    if (chapter) renderElement(tree, chapter, el);
  }

  // Render dirty milestones.
  for (const milestoneId of dirty.milestones) {
    const m = state.milestones.get(milestoneId);
    if (m) renderMilestone(tree, m);
    // Deleted milestone: writeTree will prune its directory.
  }

  // Render dirty scenarios.
  for (const scenarioId of dirty.scenarios) {
    const sc = state.scenarios.get(scenarioId);
    if (!sc) continue;
    const chapter = state.chapters.get(sc.chapterId);
    if (chapter) renderScenario(tree, chapter, sc);
  }

  // Render dirty HTML snippets.
  for (const slug of dirty.htmlSnippets) {
    const snippet = state.htmlSnippets.get(slug);
    if (snippet) renderHtmlSnippet(tree, snippet);
    // Deleted snippet: writeTree will remove its files.
  }

  // Render dirty shared lane details.
  for (const key of dirty.sharedLaneDetails) {
    const entry = state.sharedLaneDetails.get(key);
    if (!entry || entry.members.size === 0 || entry.body.length === 0) continue;
    const { type, name } = parseLaneDetailsKey(entry.key);
    const t = sanitizeSegment(type, "lane");
    const n = sanitizeSegment(name, "unnamed");
    tree.set(`lane-details/${t}/${n}/details.md`, markdown(entry.body));
  }

  return tree;
}

// ─────────────────────── path builders ───────────────────────

function chapterDir(chapter: ChapterState): string {
  return `chapters/${chapter.id}`;
}
function sliceDir(chapter: ChapterState, slice: SliceState): string {
  return `${chapterDir(chapter)}/slices/${slice.id}`;
}
function laneDir(chapter: ChapterState, lane: LaneState): string {
  return `${chapterDir(chapter)}/lanes/${lane.id}`;
}
function elementDir(chapter: ChapterState, el: ElementState): string {
  return `${chapterDir(chapter)}/elements/${el.id}`;
}

// ─────────────────────── chapter ───────────────────────

function renderChapter(tree: DesiredTree, state: ModelState, chapter: ChapterState): void {
  const dir = chapterDir(chapter);
  tree.set(
    `${dir}/chapter.json`,
    json({
      id: chapter.id,
      name: chapter.name,
      context: chapter.context,
      index: chapter.index,
      mode: chapter.mode,
      sliceOrder: chapter.sliceOrder,
      laneOrder: chapter.laneOrder,
    }),
  );
  tree.set(`${dir}/index.md`, renderChapterIndex(state, chapter));

  const slices = slicesOfChapter(state, chapter.id);
  const lanes = lanesOfChapter(state, chapter.id);

  for (const slice of slices) {
    renderSlice(tree, state, chapter, slice);
  }

  // Lanes rendered once at chapter level — no longer nested under each slice.
  for (const lane of lanes) {
    renderLane(tree, chapter, lane);
  }

  // Elements rendered flat at chapter level.
  for (const lane of lanes) {
    for (const slice of slices) {
      for (const el of elementsInCell(state, lane.id, slice.id)) {
        renderElement(tree, chapter, el);
      }
    }
  }

  // Render scenarios for this chapter.
  for (const scenario of state.scenarios.values()) {
    if (scenario.chapterId === chapter.id) {
      renderScenario(tree, chapter, scenario);
    }
  }
}

function renderChapterIndex(state: ModelState, chapter: ChapterState): string {
  const lines: string[] = [GENERATED_MARKER, `# ${chapter.name}`, ""];
  lines.push(`- **Context:** ${chapter.context}`, `- **Mode:** ${chapter.mode}`, "");
  lines.push("## Slices", "");
  const slices = slicesOfChapter(state, chapter.id);
  if (slices.length === 0) {
    lines.push("_No slices._");
  } else {
    for (const slice of slices) {
      const status = slice.status ? ` — \`${slice.status}\`` : "";
      lines.push(`${slice.index + 1}. **${slice.label}**${status}`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

// ─────────────────────── slice ───────────────────────

function renderSlice(
  tree: DesiredTree,
  _state: ModelState,
  chapter: ChapterState,
  slice: SliceState,
): void {
  const dir = sliceDir(chapter, slice);
  tree.set(
    `${dir}/slice.json`,
    json({
      id: slice.id,
      label: slice.label,
      index: slice.index,
      status: slice.status,
      width: slice.width,
      icon: slice.icon,
      milestoneId: slice.milestoneId,
      milestoneName: slice.milestoneName,
      assignee: slice.assignee,
      estimate: slice.estimate,
      timeSpent: slice.timeSpent,
    }),
  );
  tree.set(`${dir}/details.md`, markdown(slice.details));
  renderComments(tree, `${dir}/comments`, slice.comments);
}

// ─────────────────────── lane (once per chapter) ───────────────────────

function renderLane(
  tree: DesiredTree,
  chapter: ChapterState,
  lane: LaneState,
): void {
  const dir = laneDir(chapter, lane);
  tree.set(
    `${dir}/lane.json`,
    json({
      id: lane.id,
      label: lane.label,
      type: lane.type,
      index: lane.index,
      height: lane.height,
      icon: lane.icon,
    }),
  );
}

// ─────────────────────── element ───────────────────────

function renderElement(
  tree: DesiredTree,
  chapter: ChapterState,
  el: ElementState,
): void {
  const dir = elementDir(chapter, el);
  tree.set(
    `${dir}/element.json`,
    json({
      id: el.id,
      type: el.type,
      name: el.name,
      context: el.context,
      laneId: el.laneId,
      sliceId: el.sliceId,
      index: el.index,
      icon: el.icon,
      noArrowSource: el.noArrowSource,
      noArrowTarget: el.noArrowTarget,
    }),
  );
  tree.set(`${dir}/description.md`, markdown(el.description));
  tree.set(`${dir}/details.md`, markdown(el.details));
  if (el.playFunction !== undefined) {
    tree.set(`${dir}/play-function.ts`, el.playFunction);
  }
  if (el.playType !== undefined) {
    tree.set(`${dir}/play-type.ts`, `type Payload = ${el.playType}`);
  }
  renderComments(tree, `${dir}/comments`, el.comments);
}

// ─────────────────────── comments ───────────────────────

function renderComments(tree: DesiredTree, baseDir: string, comments: Comment[]): void {
  for (const c of comments) {
    const seg = `${sanitizeSegment(c.createdAt ?? "", c.id)}_${nameSlug(c.id, "")}`;
    const dir = `${baseDir}/${seg}`;
    tree.set(
      `${dir}/comment.json`,
      json({ id: c.id, author: c.author, userId: c.userId, createdAt: c.createdAt }),
    );
    tree.set(`${dir}/comment.md`, markdown(c.text));
  }
}

// ─────────────────────── scenario ───────────────────────

function renderScenario(
  tree: DesiredTree,
  chapter: ChapterState,
  sc: ScenarioState,
): void {
  const dir = `${chapterDir(chapter)}/scenarios/${sc.id}`;
  tree.set(
    `${dir}/scenario.json`,
    json({
      id: sc.id,
      chapterId: sc.chapterId,
      name: sc.name,
      clock: sc.clock,
      initialState: Object.keys(sc.initialState).length > 0 ? sc.initialState : undefined,
      seededEvents: sc.seededEvents.length > 0 ? sc.seededEvents : undefined,
      interactions: sc.interactions.length > 0 ? sc.interactions : undefined,
      expectations: sc.expectations.length > 0 ? sc.expectations : undefined,
      createdAt: sc.createdAt,
      updatedAt: sc.updatedAt,
    }),
  );
}

// ─────────────────────── shared details ───────────────────────

function renderSharedLaneDetails(tree: DesiredTree, state: ModelState): void {
  for (const entry of state.sharedLaneDetails.values()) {
    if (entry.members.size === 0 || entry.body.length === 0) continue;
    const { type, name } = parseLaneDetailsKey(entry.key);
    const t = sanitizeSegment(type, "lane");
    const n = sanitizeSegment(name, "unnamed");
    tree.set(`lane-details/${t}/${n}/details.md`, markdown(entry.body));
  }
}

// ─────────────────────── milestone ───────────────────────

function renderMilestone(tree: DesiredTree, m: MilestoneState): void {
  const dir = `milestones/${m.id}`;
  tree.set(
    `${dir}/milestone.json`,
    json({
      id: m.id,
      name: m.name,
      deadline: m.deadline,
      color: m.color,
      isCompleted: m.isCompleted,
      completedAt: m.completedAt,
      createdAt: m.createdAt,
      updatedAt: m.updatedAt,
      slices: m.slices,
    }),
  );
  tree.set(`${dir}/description.md`, markdown(m.description));
}

// ─────────────────────── html snippets ───────────────────────

/**
 * Render a workspace-level HTML snippet.
 * Stored as `html-snippets/[slug].html` — the raw HTML content is the file body.
 * A companion `[slug].json` carries the slug, name, and timestamps for metadata access.
 */
function renderHtmlSnippet(tree: DesiredTree, snippet: HtmlSnippetState): void {
  const safeSlug = sanitizeSegment(snippet.slug, "snippet");
  tree.set(`html-snippets/${safeSlug}.html`, snippet.snippet);
  tree.set(
    `html-snippets/${safeSlug}.json`,
    json({
      slug: snippet.slug,
      name: snippet.name,
      createdAt: snippet.createdAt,
      updatedAt: snippet.updatedAt,
    }),
  );
}

// ─────────────────────── uuid index ───────────────────────

/**
 * Build `uuid-index.json`: a flat map of `{ [uuid]: "relative/dir/path" }` covering
 * every entity whose primary json lives in a named directory (chapters, slices, lanes,
 * elements, milestones, scenarios). Agents can resolve a UUID received from a changelog
 * event or MCP call to a local path in O(1) without recursing the tree.
 */
function renderUuidIndex(tree: DesiredTree, state: ModelState): void {
  const index: Record<string, string> = {};

  for (const chapter of state.chapters.values()) {
    const cDir = chapterDir(chapter);
    index[chapter.id] = cDir;

    const slices = slicesOfChapter(state, chapter.id);
    const lanes = lanesOfChapter(state, chapter.id);

    for (const slice of slices) {
      index[slice.id] = sliceDir(chapter, slice);
    }

    for (const lane of lanes) {
      index[lane.id] = laneDir(chapter, lane);
      for (const slice of slices) {
        for (const el of elementsInCell(state, lane.id, slice.id)) {
          index[el.id] = elementDir(chapter, el);
        }
      }
    }

    for (const scenario of state.scenarios.values()) {
      if (scenario.chapterId === chapter.id) {
        index[scenario.id] = `${cDir}/scenarios/${scenario.id}`;
      }
    }
  }

  for (const milestone of state.milestones.values()) {
    index[milestone.id] = `milestones/${milestone.id}`;
  }

  // Stable output: sort by uuid so diffs are deterministic.
  const sorted: Record<string, string> = {};
  for (const key of Object.keys(index).sort()) {
    sorted[key] = index[key];
  }
  tree.set("uuid-index.json", JSON.stringify(sorted, null, 2) + "\n");
}

// ─────────────────────── content helpers ───────────────────────

/** Stable, pretty JSON with a trailing newline. `undefined` fields are dropped. */
function json(value: Record<string, unknown>): string {
  const clean: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(value)) {
    if (v !== undefined) clean[k] = v;
  }
  return JSON.stringify(clean, null, 2) + "\n";
}

/** Markdown file body: trimmed, with a trailing newline. Empty stays empty. */
function markdown(body: string): string {
  const text = typeof body === "string" ? body.trim() : "";
  return text.length > 0 ? `${text}\n` : "";
}
